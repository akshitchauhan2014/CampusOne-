from PySide6.QtCore import Qt
from PySide6.QtGui import QColor, QPainter, QPainterPath, QLinearGradient, QPen
from PySide6.QtWidgets import QFrame, QWidget


class LoginCard(QFrame):
    def paintEvent(self, event):
        painter = QPainter(self)
        painter.setRenderHint(QPainter.Antialiasing)
        bounds = self.rect()
        card_path = QPainterPath()
        card_path.addRoundedRect(bounds.adjusted(0, 0, -1, -1), 18, 18)
        painter.setClipPath(card_path)
        painter.fillPath(card_path, QColor("#C8D9EB"))

        header_path = QPainterPath()
        header_path.moveTo(0, 18)
        header_path.quadTo(0, 0, 18, 0)
        header_path.lineTo(bounds.width() - 18, 0)
        header_path.quadTo(bounds.width(), 0, bounds.width(), 18)
        header_path.lineTo(bounds.width(), 218)
        header_path.cubicTo(bounds.width() * .72, 242, bounds.width() * .48, 196, 0, 262)
        header_path.closeSubpath()
        gradient = QLinearGradient(0, 0, bounds.width(), bounds.height() * .7)
        gradient.setColorAt(0, QColor("#102B53"))
        gradient.setColorAt(.55, QColor("#193F70"))
        gradient.setColorAt(1, QColor("#315E92"))
        painter.fillPath(header_path, gradient)

        wave = QPainterPath()
        wave.moveTo(0, 238)
        wave.cubicTo(bounds.width() * .25, 184, bounds.width() * .48, 246, bounds.width(), 166)
        wave.lineTo(bounds.width(), 242)
        wave.cubicTo(bounds.width() * .72, 276, bounds.width() * .44, 227, 0, 294)
        wave.closeSubpath()
        painter.fillPath(wave, QColor(66, 112, 163, 190))

        wave = QPainterPath()
        wave.moveTo(0, 286)
        wave.cubicTo(bounds.width() * .27, 240, bounds.width() * .52, 312, bounds.width(), 222)
        wave.lineTo(bounds.width(), 300)
        wave.cubicTo(bounds.width() * .69, 332, bounds.width() * .39, 281, 0, 356)
        wave.closeSubpath()
        painter.fillPath(wave, QColor(117, 157, 197, 175))

        wave = QPainterPath()
        wave.moveTo(0, 335)
        wave.cubicTo(bounds.width() * .28, 291, bounds.width() * .58, 358, bounds.width(), 282)
        wave.lineTo(bounds.width(), bounds.height())
        wave.lineTo(0, bounds.height())
        wave.closeSubpath()
        painter.fillPath(wave, QColor("#C8D9EB"))


